package compiler.str;
import java.util.ArrayList;

class StrCodegen {
    private ArrayList<Declaration> declarations;
    private ArrayList<String> names;
    private ArrayList<String> values;
    private boolean standalone = false;
    private String assembly;

    public void read_Declarations(ArrayList<Declaration> declarations) {
        this.declarations = declarations;
        this.names = new ArrayList<String>();
        this.values = new ArrayList<String>();
        this.assembly = "";
    }

    public void setStandalone(boolean standalone) {
        this.standalone = standalone;
    }
    private String evaluate(Expr e) {
        if (e instanceof StringLiteral) {
            StringLiteral s = (StringLiteral) e;
            return s.getValue();
        } else if (e instanceof VarRef) {
            VarRef v = (VarRef) e;
            int index = names.indexOf(v.getName());
            return values.get(index);
        } else {
            Concat c = (Concat) e;
            return evaluate(c.getLeft()) + evaluate(c.getRight());
        }
    }

    public void generate() {
        String data = "";
        String dumpData = "";
        String dumpCode = "";

        for (int i = 0; i < declarations.size(); i++) {
            Declaration d = declarations.get(i);
            String name = d.getName();

            String text = evaluate(d.getValue());
            names.add(name);
            values.add(text);

            data = data + "s_" + name + ": db \"" + text + "\", 0\n";

            dumpData = dumpData + "d_" + name + ": db \"" + name + "=" + text + "\", 10\n";
            dumpData = dumpData + "l_" + name + " equ $ - d_" + name + "\n";

            dumpCode = dumpCode + "    mov eax, 1              ; sys_write\n";
            dumpCode = dumpCode + "    mov edi, 1              ; stdout\n";
            dumpCode = dumpCode + "    lea rsi, [d_" + name + "]\n";
            dumpCode = dumpCode + "    mov edx, l_" + name + "\n";
            dumpCode = dumpCode + "    syscall\n";
        }

        String asm = "; Generated by the RKCC String module\n";
        asm = asm + "; Target: x86-64, NASM, Intel syntax.  Strings end with 0.\n";
        asm = asm + "bits 64\n";
        asm = asm + "default rel\n\n";

        asm = asm + "section .data\n" + data;
        if (standalone) {
            asm = asm + dumpData;
        }

        asm = asm + "\nsection .text\n";
        asm = asm + "global str_main\n";
        asm = asm + "str_main:\n";
        asm = asm + "    ret\n";

        if (standalone) {
            asm = asm + "\nglobal _start\n";
            asm = asm + "_start:\n";
            asm = asm + "    call str_main\n";
            asm = asm + dumpCode;
            asm = asm + "    mov eax, 60             ; sys_exit\n";
            asm = asm + "    xor edi, edi\n";
            asm = asm + "    syscall\n";
        }
        asm = asm + "\nsection .note.GNU-stack noalloc noexec nowrite progbits\n";
        assembly = asm;
    }
    public String getAssembly() {
        return assembly;
    }
    public void display() {
        System.out.println(assembly);
    }
}